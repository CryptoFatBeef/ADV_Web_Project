"""
verification/checks/test_rbac_matrix.py

RBAC matrix tests: 7 roles × CRM routes → expected HTTP status (200/403/302).

Key facts confirmed from the codebase:
  - RoleRequiredMixin (apps/accounts/mixins.py):
      unauthenticated → 302 redirect to LOGIN_URL (handle_no_permission)
      authenticated + wrong role → 403 PermissionDenied (raised directly)
  - Django's PermissionDenied returns HTTP 403 regardless of DEBUG=True.
  - Role introspection: each view's `roles` class attribute is read at runtime.
    Views with only LoginRequiredMixin (no RoleRequiredMixin) → 200 for all roles.

RBAC matrix (derived from reading each app's views.py):

  VIEW                    ALLOWED ROLES
  ─────────────────────────────────────────────────────────────────────
  members:member_list     GRANDMASTER, DEPUTY_GRANDMASTER, ADMIN, COACH
  members:member_edit     GRANDMASTER, DEPUTY_GRANDMASTER, ADMIN
  dojos:dojo_list         All authenticated (LoginRequiredMixin only)
  events:event_list       All authenticated (LoginRequiredMixin only)
  events:event_create     GRANDMASTER, DEPUTY_GRANDMASTER, ADMIN
  activities:activity_list  All authenticated (LoginRequiredMixin only)
  skills:skill_list       All authenticated (LoginRequiredMixin only)
  fees:fee_list           GRANDMASTER, DEPUTY_GRANDMASTER, ADMIN
  payments:payment_list   GRANDMASTER, DEPUTY_GRANDMASTER, ADMIN
  communications:inbox    GRANDMASTER, DEPUTY_GRANDMASTER, ADMIN
  cms:page_list           GRANDMASTER, DEPUTY_GRANDMASTER, EDITOR
  matches:match_list      All authenticated (LoginRequiredMixin only)
  chatbot:chatbot         All authenticated (LoginRequiredMixin only)
  accounts:dashboard      All authenticated (LoginRequiredMixin only)

Credentials are read from verification/fixtures/test_credentials.csv
(generated by generate_credentials.py, loaded by seed_test_users).
"""
import csv
from pathlib import Path

import pytest
from django.urls import reverse

from verification.docs_data.role_capability_matrix import PRIMARY_USERNAME_BY_ROLE

CREDENTIALS_CSV = (
    Path(__file__).resolve().parent.parent / "fixtures" / "test_credentials.csv"
)

ALL_ROLES = [
    "GRANDMASTER",
    "DEPUTY_GRANDMASTER",
    "ADMIN",
    "EDITOR",
    "COACH",
    "MEMBER",
    "PARENT",
]

ADMIN_ROLES = {"GRANDMASTER", "DEPUTY_GRANDMASTER", "ADMIN"}
COACH_ROLES = {"GRANDMASTER", "DEPUTY_GRANDMASTER", "ADMIN", "COACH"}
EDITOR_ROLES = {"GRANDMASTER", "DEPUTY_GRANDMASTER", "EDITOR"}
ALL_AUTH = set(ALL_ROLES)

# (url_name, url_kwargs, allowed_roles_set)
RBAC_MATRIX = [
    ("accounts:dashboard",       {},  ALL_AUTH),
    ("members:member_list",      {},  COACH_ROLES),
    ("dojos:dojo_list",          {},  ALL_AUTH),
    ("events:event_list",        {},  ALL_AUTH),
    ("events:event_create",      {},  ADMIN_ROLES),
    ("activities:activity_list", {},  ALL_AUTH),
    ("skills:skill_list",        {},  ALL_AUTH),
    ("fees:fee_list",            {},  ADMIN_ROLES),
    ("payments:payment_list",    {},  ADMIN_ROLES),
    ("communications:inbox",     {},  ADMIN_ROLES),
    ("cms:page_list",            {},  EDITOR_ROLES),
    ("matches:match_list",       {},  ALL_AUTH),
    ("chatbot:chatbot",          {},  ALL_AUTH),
]


def _load_credentials() -> dict[str, str]:
    """
    Returns {username: password} from test_credentials.csv.
    Keyed by username, not role, since v2 of the CSV has multiple personas
    per role (e.g. test_coach_a/test_coach_b) — role-level RBAC tests use
    PRIMARY_USERNAME_BY_ROLE to pick one canonical persona per role.
    """
    if not CREDENTIALS_CSV.exists():
        return {}
    with open(CREDENTIALS_CSV, encoding="utf-8") as f:
        return {row["username"]: row["password"] for row in csv.DictReader(f)}


def _username(role: str) -> str:
    return PRIMARY_USERNAME_BY_ROLE[role]


# ---------------------------------------------------------------------------
# Unauthenticated access → 302 to login
# ---------------------------------------------------------------------------

@pytest.mark.rbac
@pytest.mark.django_db
@pytest.mark.parametrize("url_name,url_kwargs,_allowed", RBAC_MATRIX)
def test_unauthenticated_crm_redirects_to_login(client, seed_test_users_in_db, url_name, url_kwargs, _allowed):
    """Unauthenticated GET to any CRM route must redirect (302) to the login page."""
    url = reverse(url_name, kwargs=url_kwargs)
    response = client.get(url)
    assert response.status_code == 302, (
        f"Expected 302 redirect for unauthenticated {url_name}, "
        f"got {response.status_code}"
    )
    assert "/accounts/login/" in response["Location"], (
        f"Redirect for {url_name} should point to /accounts/login/, "
        f"got: {response.get('Location', '')}"
    )


# ---------------------------------------------------------------------------
# Role-based access: 200 if allowed, 403 if not
# ---------------------------------------------------------------------------

@pytest.mark.rbac
@pytest.mark.django_db
@pytest.mark.parametrize("role", ALL_ROLES)
@pytest.mark.parametrize("url_name,url_kwargs,allowed_roles", RBAC_MATRIX)
def test_rbac_matrix(client, seed_test_users_in_db, role, url_name, url_kwargs, allowed_roles):
    """
    For each role × CRM route: authenticated users get 200 (if allowed) or 403 (if not).
    Users are created in the test DB by the session-scoped seed_test_users_in_db fixture
    in verification/conftest.py (no external DB seeding needed).
    """
    username = _username(role)
    creds = _load_credentials()
    password = creds.get(username)
    if not password:
        pytest.skip(f"No credentials for {username} in test_credentials.csv")

    logged_in = client.login(username=username, password=password)
    if not logged_in:
        pytest.skip(f"Login failed for {username} (test DB seeding may have failed)")

    url = reverse(url_name, kwargs=url_kwargs)
    response = client.get(url)
    expected = 200 if role in allowed_roles else 403
    assert response.status_code == expected, (
        f"Role={role} GET {url_name} ({url}): "
        f"expected {expected}, got {response.status_code}. "
        f"Allowed roles: {sorted(allowed_roles)}"
    )
